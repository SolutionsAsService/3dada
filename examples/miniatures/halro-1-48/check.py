#!/usr/bin/env python3
"""Check the kit through the unified-CAD-MCP miniature_* tools (in-process MCP client, the same calls an agent makes).

Run with a Python that has unified-cad-mcp installed (e.g. its .venv):  python check.py
Writes reports/printability.json and reports/report.md; exits 1 if a part fails or the spec drifted from the tools.
"""
import asyncio
import json
from pathlib import Path
import sys

from fastmcp import Client

from unified_cad_mcp.config import AirframeConfig, Configuration
from unified_cad_mcp.server import create_server

HERE = Path(__file__).resolve().parent
S = json.loads((HERE / "spec.json").read_text())
KIT, R, HERO = S["kit"], S["real_mm"], S["heroic"]
# Print setup per part: the base sits flat on the plate; the others go on supports in the orientation support_plan picks.
SETUP = {"base": {"on_build_plate": True, "plan": False}, "stand": {"on_build_plate": False, "plan": False},
         "airframe": {"on_build_plate": False, "plan": True}}


async def main() -> int:
    cfg = Configuration(project_root=str(HERE), drone_tools=True, backends={},
                        airframe=AirframeConfig(freecad_python="unused", output_root=str(HERE / "stl")))
    out, problems = {}, []
    async with Client(create_server(cfg), timeout=900) as c:
        call = lambda tool, args: c.call_tool(tool, args)
        scale = (await call("miniature_scale_convert", {"scale": S["scale"], "process": S["process"], "features": [
            {"name": "span", "real_mm": R["span"]},
            {"name": "pod width", "kind": "wall", "real_mm": 180},
            {"name": "wing root thickness (14 %)", "kind": "wall", "real_mm": 53},
            {"name": "wing tip thickness (12 %)", "kind": "wall", "real_mm": 24},
            {"name": "tail thickness (10 %)", "kind": "wall", "real_mm": 20},
            {"name": "tail boom", "kind": "wire", "real_mm": R["booms"]["diameter"], "wire_length_real_mm": R["booms"]["x"][1] - R["booms"]["x"][0]},
            {"name": "prop blade thickness", "kind": "wall", "real_mm": 12}]})).data
        out["scale_convert"] = scale
        joints = {}
        for key, host in (("lower_joint", 2 * KIT["base"]["mound"]["radius_mm"]), ("upper_joint", 5.4)):
            j = KIT[key]
            r = (await call("miniature_base_and_peg", {"base": str(KIT["base"]["diameter_mm"]), "magnet": KIT["base"]["magnet"],
                                                       "process": S["process"], "base_height_mm": KIT["base"]["height_mm"],
                                                       "peg_diameter_mm": j["peg_diameter_mm"], "host_section_mm": host})).data
            joints[key] = r
            peg = r["peg"]
            want = {"peg_length_mm": peg["length_mm"], "flat_at_mm": peg["key"]["flat_at_mm_from_axis"], "socket_diameter_mm": peg["socket_diameter_mm"],
                    "socket_flat_at_mm": peg["socket_flat_at_mm_from_axis"], "socket_depth_mm": peg["socket_depth_mm"], "tip_chamfer_mm": peg["tip_chamfer_mm"]}
            problems += [f"spec {key}.{k} = {j[k]} but the tool says {v}" for k, v in want.items() if abs(j[k] - v) > 1e-6]
            pocket = r["magnet_pocket"]
            problems += [f"spec base.{k} = {KIT['base'][k]} but the tool says {pocket[k]}" for k in ("pocket_diameter_mm", "pocket_depth_mm")
                         if abs(KIT["base"][k] - pocket[k]) > 1e-6]
            problems += [f"{key}: {c['name']} failed" for c in r["checks"] if not c["pass"]]
        out["base_and_peg"] = joints
        out["parts"] = {}
        for part, setup in SETUP.items():
            stl = f"halro-1-48-{part}.stl"
            rot = [0.0, 0.0, 0.0]
            entry = {}
            if setup["plan"]:
                plan = (await call("miniature_support_plan", {"stl_path": stl, "process": S["process"]})).data
                entry["support_plan"] = plan
                rot = plan["best"][0]["rotate_deg"]
            r = (await call("miniature_printability_check", {"stl_path": stl, "process": S["process"], "rotate_deg": rot,
                                                             "on_build_plate": setup["on_build_plate"],
                                                             "build_volume_mm": [153.36, 77.76, 165]})).data
            entry["printability"] = r
            out["parts"][part] = entry
            problems += [f"{part}: {c['name']} = {c['value']} (limit {c['limit']})" for c in r["checks"] if not c["pass"] and c["severity"] == "fail"]
    (HERE / "reports" / "printability.json").write_text(json.dumps(out, indent=1))
    lines = ["# HALRO 1:48 kit: miniature_* tool report", "", "Generated by check.py through the unified-CAD-MCP miniature_* tools "
             f"(process {S['process']}, build volume 153.36 x 77.76 x 165 mm, an 8K 7-inch class MSLA plate).", "",
             "## Scale (miniature_scale_convert)", "", "| Feature | Real mm | 1:48 mm | Limit | Printable |", "|---|---|---|---|---|"]
    for f in out["scale_convert"]["features"]:
        lines.append(f"| {f['name']} | {f['real_mm']} | {f['model_mm']} | {f.get('limit_mm', '')} | {'yes' if f['printable'] else 'NO -> thickened'} |")
    lines += ["", "## Parts (miniature_printability_check)", "", "| Part | Orientation (rx, ry, rz) | Volume mm3 | Resin g | Min wall mm | Islands | Largest cup mm2 | Largest layer mm2 | Fails | Warnings |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for part, e in out["parts"].items():
        r = e["printability"]
        cup = max((c["max_area_mm2"] for c in r["suction_cups"]), default=0)
        fails = [c["name"] for c in r["checks"] if not c["pass"] and c["severity"] == "fail"]
        lines.append(f"| {part} | {r['rotate_deg']} {'on plate' if r['on_build_plate'] else 'on supports'} | {r['volume_mm3']} | {r['mass_g']} | "
                     f"{r['thickness']['min_mm']} | {r['islands']['count']} | {cup} | {r['largest_layer']['area_mm2']} | {', '.join(fails) or 'none'} | {', '.join(r['warnings']) or 'none'} |")
    plan = out["parts"]["airframe"]["support_plan"]
    lines += ["", "## Airframe orientation (miniature_support_plan)", "", f"As modelled: largest layer {plan['as_modelled']['max_layer_area_mm2']} mm2, "
              f"support area {plan['as_modelled']['support_area_mm2']} mm2. Best: rotate {plan['best'][0]['rotate_deg']}, largest layer "
              f"{plan['best'][0]['max_layer_area_mm2']} mm2, support area {plan['best'][0]['support_area_mm2']} mm2.", "",
              "## Result", "", "PASS: every fail-severity check passes for every part." if not problems else "FAIL:\n" + "\n".join(f"- {p}" for p in problems), ""]
    (HERE / "reports" / "report.md").write_text("\n".join(lines))
    print("\n".join(lines))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
